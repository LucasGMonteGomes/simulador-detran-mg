-- Simulados realizados e as respostas de cada um.

CREATE TABLE simulado (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modo           VARCHAR(10) NOT NULL CHECK (modo IN ('PROVA', 'TREINO')),
    -- Regras copiadas no início do simulado: mudar a configuração depois não altera o histórico.
    total_questoes INTEGER     NOT NULL CHECK (total_questoes > 0),
    nota_corte     INTEGER     NOT NULL,
    iniciado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- NULL = sem limite de tempo (Modo Treino).
    expira_em      TIMESTAMPTZ,
    finalizado_em  TIMESTAMPTZ,
    acertos        INTEGER,
    aprovado       BOOLEAN,
    CHECK (nota_corte BETWEEN 0 AND total_questoes),
    CHECK (expira_em IS NULL OR expira_em > iniciado_em),
    CHECK (acertos BETWEEN 0 AND total_questoes),
    -- Resultado existe se, e somente se, o simulado foi finalizado.
    CHECK ((finalizado_em IS NULL) = (acertos IS NULL)),
    CHECK ((finalizado_em IS NULL) = (aprovado IS NULL))
);

CREATE INDEX idx_simulado_finalizados ON simulado (modo, finalizado_em) WHERE finalizado_em IS NOT NULL;

CREATE TABLE resposta (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    simulado_id    BIGINT      NOT NULL REFERENCES simulado (id) ON DELETE CASCADE,
    questao_id     BIGINT      NOT NULL REFERENCES questao (id),
    ordem          INTEGER     NOT NULL CHECK (ordem > 0),
    -- NULL = questão deixada em branco.
    alternativa_id BIGINT,
    -- Gabarito congelado na finalização; NULL enquanto o simulado está em andamento.
    correta        BOOLEAN,
    tempo_gasto_ms BIGINT      NOT NULL DEFAULT 0 CHECK (tempo_gasto_ms >= 0),
    respondida_em  TIMESTAMPTZ,
    UNIQUE (simulado_id, questao_id),
    UNIQUE (simulado_id, ordem),
    FOREIGN KEY (alternativa_id, questao_id) REFERENCES alternativa (id, questao_id)
);

CREATE INDEX idx_resposta_questao ON resposta (questao_id);
