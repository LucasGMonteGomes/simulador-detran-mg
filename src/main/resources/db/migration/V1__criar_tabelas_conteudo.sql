-- Conteúdo da prova: disciplinas oficiais (Res. CONTRAN 789/2020), subtemas e questões.

CREATE TABLE disciplina (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo        VARCHAR(50)  NOT NULL UNIQUE,
    nome          VARCHAR(120) NOT NULL,
    -- Carga horária do curso teórico; define a proporção de questões no Modo Prova.
    carga_horaria INTEGER      NOT NULL CHECK (carga_horaria > 0)
);

CREATE TABLE subtema (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    disciplina_id BIGINT       NOT NULL REFERENCES disciplina (id),
    codigo        VARCHAR(80)  NOT NULL UNIQUE,
    nome          VARCHAR(150) NOT NULL
);

CREATE INDEX idx_subtema_disciplina ON subtema (disciplina_id);

CREATE TABLE questao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subtema_id       BIGINT       NOT NULL REFERENCES subtema (id),
    -- Código estável vindo do arquivo de questões (ex.: LEG-0001); versao muda a cada revisão.
    codigo           VARCHAR(30)  NOT NULL,
    versao           INTEGER      NOT NULL DEFAULT 1 CHECK (versao > 0),
    enunciado        TEXT         NOT NULL,
    imagem           VARCHAR(255),
    explicacao       TEXT         NOT NULL,
    referencia_legal VARCHAR(150),
    ativa            BOOLEAN      NOT NULL DEFAULT TRUE,
    criada_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (codigo, versao)
);

-- Só uma versão ativa por código: revisar uma questão desativa a anterior em vez de sobrescrevê-la.
CREATE UNIQUE INDEX uq_questao_versao_ativa ON questao (codigo) WHERE ativa;
CREATE INDEX idx_questao_subtema ON questao (subtema_id);

CREATE TABLE alternativa (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    questao_id BIGINT  NOT NULL REFERENCES questao (id) ON DELETE CASCADE,
    ordem      INTEGER NOT NULL CHECK (ordem BETWEEN 1 AND 5),
    texto      TEXT    NOT NULL,
    correta    BOOLEAN NOT NULL,
    UNIQUE (questao_id, ordem),
    -- Alvo da FK composta em resposta: garante que a alternativa escolhida pertence à questão.
    UNIQUE (id, questao_id)
);

-- No máximo uma alternativa correta por questão. "Pelo menos uma" fica a cargo do importador.
CREATE UNIQUE INDEX uq_alternativa_uma_correta ON alternativa (questao_id) WHERE correta;
